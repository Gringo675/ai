import { createStep, createWorkflow } from '@mastra/core/workflows'
import { z } from 'zod'
import { testAgent } from '../agents/testAgent'

const inputSchema = z.object({
  message: z.string().describe('The message to send to testAgent'),
})

const outputSchema = z.object({
  response: z.string().describe('The response generated by testAgent'),
})

const testStep = createStep({
  id: 'test-step',
  description: 'Executes testAgent with the provided message',
  inputSchema,
  outputSchema,
  execute: async ({ inputData, abortSignal }) => {
    const response = await testAgent.generate(inputData.message, {
      abortSignal,
    })

    return {
      response: response.text ?? '',
    }
  },
})

export const testWorkflow = createWorkflow({
  id: 'test-workflow',
  inputSchema,
  outputSchema,
  // retryConfig: {
  //   attempts: 1,
  //   delay: 5000,
  // },
})
  .then(testStep)
  .commit()
